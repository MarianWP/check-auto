import { it, expect } from "vitest";
import { plural, count } from "../src/logic/text";

it("українська множина", () => {
  const p = n => count(n, "пункт", "пункти", "пунктів");
  expect([1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 101, 103, 111, 0].map(p)).toEqual([
    "1 пункт", "2 пункти", "4 пункти", "5 пунктів", "11 пунктів", "12 пунктів", "14 пунктів",
    "21 пункт", "22 пункти", "25 пунктів", "101 пункт", "103 пункти", "111 пунктів", "0 пунктів"
  ]);
  expect(plural(3, "проблема", "проблеми", "проблем")).toBe("проблеми");
});
